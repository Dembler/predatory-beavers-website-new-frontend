/** Editorial wording for public text, without changing the archived source. */
export function clubCopy(value: string): string {
  const substitutions: [RegExp, string][] = [
    [
      /мужская и женская баскетбольные команды/giu,
      'мужская баскетбольная команда и команда девушек',
    ],
    [/мужская и женская команды/giu, 'мужская команда и команда девушек'],
    [/мужской и женской команд(?![а-яё])/giu, 'мужской команды и команды девушек'],
    [/мужская и женская сборные/giu, 'мужская сборная и сборная девушек'],
    [/мужской и женской сборных/giu, 'мужской сборной и сборной девушек'],
    [/мужской и женской сборными/giu, 'мужской сборной и сборной девушек'],
    [/мужского и женского турниров/giu, 'мужского турнира и турнира девушек'],
    [/женская баскетбольная команда/giu, 'баскетбольная команда девушек'],
    [/женская команда/giu, 'команда девушек'],
    [/женской команды/giu, 'команды девушек'],
    [/женской команде/giu, 'команде девушек'],
    [/женскую команду/giu, 'команду девушек'],
    [/женской командой/giu, 'командой девушек'],
    [/женских команд/giu, 'команд девушек'],
    [/женских студенческих команд/giu, 'студенческих команд девушек'],
    [/женские команды/giu, 'команды девушек'],
    [/женская сборная/giu, 'сборная девушек'],
    [/женской сборной/giu, 'сборной девушек'],
    [/женскую сборную/giu, 'сборную девушек'],
    [/женским баскетболом/giu, 'баскетболом девушек'],
    [/женском баскетболе/giu, 'баскетболе девушек'],
    [/женского баскетбола/giu, 'баскетбола девушек'],
    [/женский баскетбол/giu, 'баскетбол девушек'],
    [/женского турнира/giu, 'турнира девушек'],
    [/женском турнире/giu, 'турнире девушек'],
    [/женский турнир/giu, 'турнир девушек'],
    [/женских встреч/giu, 'встреч девушек'],
    [/женское золото/giu, 'золото девушек'],
    [/женское серебро/giu, 'серебро девушек'],
    [/женская бронза/giu, 'бронза девушек'],
    [/женскую бронзу/giu, 'бронзу девушек'],
    [/женского 3×3/giu, '3×3 среди девушек'],
    [/в женском(?=\s*—)/giu, 'в турнире девушек'],
    [/— женского(?= и)/giu, '— команды девушек'],
    [/женская(?=\s+(?:—|завоевала|ВГУ))/giu, 'команда девушек'],
    [/женщинах/giu, 'девушках'],
    [/женщинами/giu, 'девушками'],
    [/женщинам/giu, 'девушкам'],
    [/женщины/giu, 'девушки'],
    [/женщин/giu, 'девушек'],
  ]
  return substitutions.reduce(
    (text, [pattern, replacement]) =>
      text.replace(pattern, (match) =>
        match[0] === match[0]?.toLocaleUpperCase('ru-RU')
          ? replacement[0]!.toLocaleUpperCase('ru-RU') + replacement.slice(1)
          : replacement,
      ),
    value,
  )
}
